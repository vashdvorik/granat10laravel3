<?php

namespace App\Support;

/**
 * Предложный падеж названий населённых пунктов: «Тирасполь» → «в Тирасполе».
 *
 * Для заголовков и описаний важно писать так, как люди ищут: «купить мышь в Тирасполе», а не «в Тирасполь».
 * Названия ПМР разобраны вручную; для остальных работают правила окончаний. Если правило ошибается,
 * в админке («Населённые пункты») можно задать форму вручную: она важнее и правил, и словаря.
 */
final class RussianLocative
{
    /** @var array<string, string> нормализованное название → предложный падеж */
    private const KNOWN = [
        'тирасполь' => 'Тирасполе',
        'новотираспольский' => 'Новотираспольском',
        'бендеры' => 'Бендерах',
        'гиска' => 'Гиске',
        'протягайловка' => 'Протягайловке',
        'слободзея' => 'Слободзее',
        'днестровск' => 'Днестровске',
        'первомайск' => 'Первомайске',
        'красное' => 'Красном',
        'парканы' => 'Парканах',
        'суклея' => 'Суклее',
        'кицканы' => 'Кицканах',
        'терновка' => 'Терновке',
        'ближний хутор' => 'Ближнем Хуторе',
        'чобручи' => 'Чобручах',
        'карагаш' => 'Карагаше',
        'глиное' => 'Глином',
        'коротное' => 'Коротном',
        'рыбница' => 'Рыбнице',
        'ержово' => 'Ержове',
        'колбасна' => 'Колбасне',
        'попенки' => 'Попенках',
        'большой молокиш' => 'Большом Молокише',
        'дубоссары' => 'Дубоссарах',
        'лунга' => 'Лунге',
        'дзержинское' => 'Дзержинском',
        'дойбаны' => 'Дойбанах',
        'григориополь' => 'Григориополе',
        'маяк' => 'Маяке',
        'малаешты' => 'Малаештах',
        'бутор' => 'Буторе',
        'ташлык' => 'Ташлыке',
        'спея' => 'Спее',
        'делакеу' => 'Делакеу',
        'каменка' => 'Каменке',
        'подойма' => 'Подойме',
        'подоймица' => 'Подоймице',
        'рашков' => 'Рашкове',
        'катериновка' => 'Катериновке',
        // города, которые часто ищут рядом с ПМР
        'кишинёв' => 'Кишинёве',
        'кишинев' => 'Кишинёве',
        'одесса' => 'Одессе',
        'москва' => 'Москве',
    ];

    /** «Тирасполе» (без предлога). */
    public static function prepositional(string $name): string
    {
        $name = trim(preg_replace('/\s+/u', ' ', $name) ?? $name);

        if ($name === '') {
            return '';
        }

        $key = mb_strtolower($name);

        if (isset(self::KNOWN[$key])) {
            return self::KNOWN[$key];
        }

        // «Дойбаны-1» → «Дойбанах-1»: склоняется только основа до дефиса
        if (str_contains($name, '-')) {
            [$head, $tail] = explode('-', $name, 2);
            $headKey = mb_strtolower($head);

            return (self::KNOWN[$headKey] ?? self::word($head)).'-'.$tail;
        }

        return implode(' ', array_map(self::word(...), explode(' ', $name)));
    }

    /** «в Тирасполе» (или «во Владимировке»). */
    public static function in(string $name): string
    {
        $form = self::prepositional($name);

        if ($form === '') {
            return '';
        }

        return (self::needsVo($form) ? 'во ' : 'в ').$form;
    }

    private static function needsVo(string $form): bool
    {
        // «во Владимировке», «во Фрунзе»: перед «в»/«ф» и согласной
        return (bool) preg_match('/^[вф][бвгджзйклмнпрстфхцчшщ]/iu', $form);
    }

    /** Одно слово по правилам окончаний. */
    private static function word(string $word): string
    {
        $lower = mb_strtolower($word);

        if (isset(self::KNOWN[$lower])) {
            return self::KNOWN[$lower];
        }

        if (mb_strlen($word) < 3) {
            return $word;
        }

        $cut = static fn (int $length, string $ending): string => mb_substr($word, 0, mb_strlen($word) - $length).$ending;
        $ends = static fn (string $suffix): bool => str_ends_with($lower, $suffix);

        return match (true) {
            // прилагательные: Новотираспольский, Большой, Красное
            $ends('ский'), $ends('цкий') => $cut(2, 'ом'),
            $ends('ый'), $ends('ой') => $cut(2, 'ом'),
            $ends('ий') => $cut(2, 'ем'),
            $ends('ое') => $cut(2, 'ом'),
            $ends('ая') => $cut(2, 'ой'),
            $ends('яя') => $cut(2, 'ей'),
            $ends('ее') => $cut(2, 'ем'),
            // неизменяемые: Делакеу, Кишиневу
            $ends('у'), $ends('ю'), $ends('э') => $word,
            // множественное число: Бендеры, Попенки
            $ends('ы') => $cut(1, 'ах'),
            $ends('и') => preg_match('/[кгхжшчщ]и$/u', $lower) ? $cut(1, 'ах') : $cut(1, 'ях'),
            // женский род и «-ея/-ия»
            $ends('ия') => $cut(1, 'и'),
            $ends('ея') => $cut(1, 'е'),
            $ends('я') => $cut(1, 'е'),
            $ends('а') => $cut(1, 'е'),
            // средний род: Ержово → Ержове
            $ends('о') => $cut(1, 'е'),
            $ends('е') => $word,
            // мужской род на «-ь»: Тирасполь → Тирасполе
            $ends('ь') => $cut(1, 'е'),
            $ends('й') => $cut(1, 'е'),
            default => $word.'е',
        };
    }
}
